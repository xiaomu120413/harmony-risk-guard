"""Generate ArkTS golden data (GoldenData.ets) from tests/golden_cases.jsonl.

Usage: python scripts/gen_golden_ts.py
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def fmt_list(vals, per_line=16):
    lines = []
    for i in range(0, len(vals), per_line):
        lines.append('  ' + ', '.join(str(v) for v in vals[i:i + per_line]) + ',')
    return '\n'.join(lines)


def main():
    rows = [json.loads(line) for line in open(ROOT / 'tests/golden_cases.jsonl',
                                               encoding='utf-8') if line.strip()]
    r = rows[0]
    ts = f"""// Auto-generated by scripts/gen_golden_ts.py from tests/golden_cases.jsonl
// Golden case for M2-B on-device parity (PyTorch CPU reference).

export const RG_SAMPLE_ID: string = {json.dumps(r['sample_id'])};
export const RG_TEXT: string = {json.dumps(r['text'], ensure_ascii=False)};
export const RG_LABELS: string[] = ['CONTINUE', 'ASK', 'BLOCK'];

export const RG_INPUT_IDS: number[] = [
{fmt_list(r['input_ids'])}
];

export const RG_ATTENTION_MASK: number[] = [
{fmt_list(r['attention_mask'])}
];

export const RG_PT_LOGITS: number[] = {json.dumps(r['pt_logits'])};
export const RG_PT_LABEL: string = {json.dumps(r['pt_label'])};
"""
    dst = ROOT / 'harmony/entry/src/main/ets/model/GoldenData.ets'
    dst.parent.mkdir(parents=True, exist_ok=True)
    dst.write_text(ts, encoding='utf-8')
    print('written', dst)


if __name__ == '__main__':
    main()
