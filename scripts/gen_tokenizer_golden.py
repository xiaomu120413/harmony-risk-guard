"""Generate ArkTS golden tokenizer data (TokenizerGolden.ets) from tests/golden_cases.jsonl.

Each golden case carries the canonical token IDs produced by the Windows-side
HuggingFace BertTokenizer. The on-device ArkTS WordPiece implementation must
reproduce these IDs exactly (M2-C parity). An extra long-text case exercises
truncation to max_length=128.

Usage: python scripts/gen_tokenizer_golden.py
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def fmt_row(vals, per_line=16, indent='      '):
    lines = []
    for i in range(0, len(vals), per_line):
        lines.append(indent + ', '.join(str(v) for v in vals[i:i + per_line]) + ',')
    return '\n'.join(lines)


def long_text_case():
    """Build a >128-token text and encode it with the real HF tokenizer."""
    from transformers import AutoTokenizer
    tok = AutoTokenizer.from_pretrained(ROOT / 'models/finetuned_last2')
    rows = [json.loads(line) for line in open(ROOT / 'tests/golden_cases.jsonl',
                                               encoding='utf-8') if line.strip()]
    text = '；'.join(r['text'] for r in rows[:6])  # ~6x normal length, >128 tokens
    enc = tok(text, truncation=True, padding='max_length', max_length=128,
              return_attention_mask=True)
    ids = [int(v) for v in enc['input_ids']]
    mask = [int(v) for v in enc['attention_mask']]
    assert ids[-1] == tok.sep_token_id, 'truncation must keep [SEP] at last position'
    return {'id': 'LONG-TRUNC-001', 'text': text, 'ids': ids, 'mask': mask}


def main():
    rows = [json.loads(line) for line in open(ROOT / 'tests/golden_cases.jsonl',
                                               encoding='utf-8') if line.strip()]
    cases = [{'id': r['sample_id'], 'text': r['text'],
              'ids': r['input_ids'], 'mask': r['attention_mask']} for r in rows]
    cases.append(long_text_case())

    entries = []
    for r in cases:
        entries.append(
            '  {\n'
            f'    id: {json.dumps(r["id"])},\n'
            f'    text: {json.dumps(r["text"], ensure_ascii=False)},\n'
            f'    ids: [\n{fmt_row(r["ids"])}\n    ],\n'
            f'    mask: [\n{fmt_row(r["mask"])}\n    ],\n'
            '  }')
    body = ',\n'.join(entries)
    ts = ('// Auto-generated by scripts/gen_tokenizer_golden.py from tests/golden_cases.jsonl\n'
          '// Canonical BertTokenizer IDs from the Windows-side HuggingFace tokenizer.\n\n'
          'export interface TokenizerCase {\n'
          '  id: string;\n'
          '  text: string;\n'
          '  ids: number[];\n'
          '  mask: number[];\n'
          '}\n\n'
          f'export const TOKENIZER_CASES: TokenizerCase[] = [\n{body}\n];\n')
    dst = ROOT / 'harmony/entry/src/main/ets/model/TokenizerGolden.ets'
    dst.write_text(ts, encoding='utf-8')
    print(f'written {dst} ({len(cases)} cases, {dst.stat().st_size} bytes)')


if __name__ == '__main__':
    main()

